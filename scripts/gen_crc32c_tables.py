#!/usr/bin/env python3
"""Regenerate with scripts/gen_crc32c_tables.py > src/crc32c_tables.h."""

POLY = 0x82F63B78


def main():
    t = [[0] * 256 for _ in range(8)]
    for b in range(256):
        c = b
        for _ in range(8):
            c = (c >> 1) ^ (POLY if c & 1 else 0)
        t[0][b] = c
    for b in range(256):
        c = t[0][b]
        for k in range(1, 8):
            c = (c >> 8) ^ t[0][c & 0xFF]
            t[k][b] = c

    print("#pragma once")
    print()
    print("/* Generated by scripts/gen_crc32c_tables.py for the eight-byte CRC loop. */")
    print()
    print('#include "pagestore/types.h"')
    print()
    print("/* Entry [k][b] is the raw CRC of b followed by k zero bytes, starting at zero. */")
    print("// clang-format off")
    print("static const u32 ps_crc32c_tab[8][256] = {")
    for k in range(8):
        print("    {")
        for i in range(0, 256, 6):
            row = ", ".join(f"0x{v:08X}u" for v in t[k][i:i + 6])
            print(f"        {row},")
        print("    },")
    print("};")
    print("// clang-format on")


if __name__ == "__main__":
    main()
